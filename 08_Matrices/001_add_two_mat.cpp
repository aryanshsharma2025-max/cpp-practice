#include<iostream>
using namespace std;
int main()
{
    int n;
    cout << "Enter the size: ";
    cin >> n;
    int a[n] , b[n];
    cout << "Enter the elements in A matrix: ";
    for (int i = 0; i< n; i++)
    {
        cout << a[i] << endl;
    }
    cout << "Enter the elements in B matrix: ";
    for (int i = 0; i< n; i++)
    {
        cout << b[i] << endl;
    }

}
